let currentLanguage = 'en';
const langListeners = new Set();

// Initialize from local storage
if (typeof window !== 'undefined') {
  try {
    const saved = localStorage.getItem('dhms_lang');
    if (saved && translations[saved]) {
      currentLanguage = saved;
      updateDocumentDirection(saved);
    }
  } catch (e) {}
}

function updateDocumentDirection(lang) {
  if (typeof document !== 'undefined') {
    const langObj = SUPPORTED_LANGUAGES.find(l => l.code === lang);
    const dir = langObj?.dir || 'ltr';
    document.documentElement.dir = dir;
    document.documentElement.lang = lang;
    if (dir === 'rtl') {
      document.body.classList.add('rtl-mode');
    } else {
      document.body.classList.remove('rtl-mode');
    }
  }
}

export function getCurrentLanguage() {
  return currentLanguage;
}

export function setLanguage(langCode) {
  if (!translations[langCode]) return;
  currentLanguage = langCode;
  try {
    localStorage.setItem('dhms_lang', langCode);
  } catch (e) {}
  updateDocumentDirection(langCode);
  langListeners.forEach(fn => {
    try { fn(langCode); } catch (e) {}
  });
}

export function subscribeLanguage(listener) {
  langListeners.add(listener);
  return () => langListeners.delete(listener);
}

export function t(key, fallback = '') {
  const dict = translations[currentLanguage] || translations.en;
  return dict[key] || translations.en[key] || fallback || key;
}
